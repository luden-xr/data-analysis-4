# 이 줄을 왼쪽부터 읽으면 (한 줄에 세가지가 겹쳐 있어서 끊어 읽어야 함!)
# sorted(pairs,...) -> pairs를 줄 세운 새 목록을 만든다.(원본 pairs는 그대로)
# key=lambda t: -t[1] "무엇을 기준으로 줄 세울까"를 알려 주는 손잡이?
# lambda t: -t[1]   이름없는 한 줄 함수 't를 받으면 -t[1]을 돌려준다'는 뜻
# t는 ("온도", 1.39)와 같은 한쌍, t[1]는 그 쌍의 숫자?
# 앞에 붙은 '-'? -> 작은 것부터 세우는게 기본이라 부호를 뒤집어 큰 것부터 세웁니다.

