def stat(values):
    """
    숫자 리스트를 받아 개수, 평균, 최대, 최소, 범위, 흔들림을 딕셔너리로 돌려줍니다.
    왜 딕셔너리로 돌려주나 - 값 여섯 개를 튜플로 돌려주면 받는 쪽에서 순서를 기억해야함
    s[3]이 최소인지 범위인지 사흘 뒤엔 모름
    딕셔너리면 s['최소'] 라고 쓰게 되어 코드가 스스로 설명합니다.
    """

    return {
        "개수": len(values),
        "평균": round(sum(values) / len(values), 2),
        "최대": max(values),
        "최소": min(values),
        "범위": round(max(values) - min(values), 2),
        "흔들림": round(
            sum([abs(t - sum(values) / len(values)) for t in values])
            / len([abs(t - sum(values) / len(values)) for t in values]),
            2,
        ),
    }


