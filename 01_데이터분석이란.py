print(
    "6)슬라이싱: temps[:3] = ",
    temps[:3],
    "|temps[-3:] = ",
    temps[-3:],
    "|temps[::-1][:3]=",
    temps[::-1][:3],
)
# 슬라이싱 세 가지를 나란히....
# temps[:3] ->앞에서 3개
# temps[3:] ->3번째 부터 끝까지!
# temps[::-1] 거꾸로 뒤집은 새 목록. 콜론 두 개 뒤의 -1이 '한 칸씩 뒤로'입니다
# temps[::-1][:3] 뒤집고 나서 앞에 3개 = 원래 목록의 마지막 3개를거꾸로 본것....


